const LEDGER: [RegExp, string][] = [
  [/^(.+) a déposé sa part$/, '$1 paid their share'],
  [/^Le cercle a été ouvert par (.+)$/, 'Circle opened by $1'],
  [/^L’ordre des tours a été tiré au sort$/, 'The payout order was drawn by lot'],
  [/^(.+) a clôturé le cycle (\d+)$/, '$1 closed cycle $2'],
  [/^Le pot a été versé à (.+)$/, 'The pot was paid out to $1'],
  [/^Le cycle (\d+) a été ouvert$/, 'Cycle $1 opened'],
  [/^(.+) a relancé (.+)$/, '$1 sent $2 a reminder'],
  [/^(.+) déclare avoir remis (.+) en espèces$/, '$1 says they handed over $2 in cash'],
  [/^(.+) par semaine · (\d+) membres$/, '$1 a week · $2 members'],
  [/^(.+) par mois · (\d+) membres$/, '$1 a month · $2 members'],
  [/^Scellé · identique pour les (\d+) membres$/, 'Sealed · identical for all $1 members'],
  [/^Les (\d+) parts étaient arrivées$/, 'All $1 shares were in'],
  [/^(.+) · vérifié auprès de l’opérateur$/, '$1 · verified with the operator'],
  [/^Espèces · validées par (.+)$/, 'Cash · confirmed by $1'],
  [/^Bénéficiaire : (.+)$/, 'Recipient: $1'],
  [/^Relance · part manquante$/, 'Reminder · missing share'],
  [/^En attente de validation$/, 'Awaiting confirmation'],
];

// Ledger lines are stored as written (append-only); translation happens on display.
export function ledgerText(text: string | null, lang: Lang) {
  if (!text || lang === 'fr') return text;
  const hit = LEDGER.find(([re]) => re.test(text));
  const out = hit ? text.replace(hit[0], hit[1]) : text;
  return out.replace(/^Carte\b/, 'Card').replace(/^Espèces\b/, 'Cash');
}
